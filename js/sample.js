export const SAMPLE_MD = `# Anchored: Hope That Holds
## Family Church Students · Sample Message

**Big idea:** ==Your hope is only as strong as what it's anchored to.==

Open your Bibles to Hebrews 6:19. While you're turning there, let me ask you a question: *what's holding you right now?* Not what you post about. What actually holds you when the week falls apart?

## 1. Everybody is anchored to something

Every one of us is tied to something we believe will keep us steady: grades, a relationship, a team, followers, a future plan. None of those are bad things. But they were never built to hold the full weight of your life.

- Grades change every semester.
- Relationships go through seasons.
- Followers move on to the next thing.

Jesus told a story about two builders in Matthew 7:24-27. Same storm. Same rain. Same wind. The only difference was **what the house was built on.**

**Note:** Pause here. Let them sit with it for a second.

## 2. God's love is not fragile

Here's what we see over and over in Scripture: God's love for you isn't based on your best week. Look at Romans 5:8. God didn't wait for us to get it together first.

Paul says it again in Rom 8:28-30, and then he asks the big question in Romans 8:31: if God is for us, who can be against us? Then he lists everything that *can't* separate us from God's love. Read Romans 8:38-39 slowly with me.

Some of you have heard John 3:16 so many times that it sounds like wallpaper. But read it like it's the first time. *For God so loved* — that's not a feeling that comes and goes. That's a decision God already made.

> "Grace isn't a reward for good behavior. It's a gift."

**Illustration:** Tell the story about the first time you went tubing on the lake and the rope snapped. Keep it under a minute.

## 3. Love that looks like something

When Paul describes what real love looks like in 1 Cor 13:4-7, it reads like a description of God's character before it's ever an instruction for us. Patient. Kind. Not keeping score.

And David, who had every reason to feel unsafe, wrote Psalm 23 as a song about a God who walks *with* him through the darkest valley — not around it.

Here's the shift: ==we don't love well so that God will love us. We love well because he already does== (1 John 4:19).

1. Receive it. Stop trying to earn what's already been given.
2. Rest in it. Your worst day doesn't change his mind about you.
3. Reflect it. Let someone this week feel what it's like to be loved without conditions.

## 4. So what do we do with this?

Ephesians 2:8-9 makes that crystal clear: grace is not something you earn. It's a gift. And gifts are received, not earned.

When anxiety shows up at 1 a.m., Philippians 4:6-7 gives us a practice, not just a promise: pray about everything, with thanksgiving, and let God's peace stand guard over your heart and mind.

And when you feel like you're going to fall, remember Jude 24 — he is able to keep you from stumbling.

## Response

Let's take a minute. Close your eyes. Ask yourself honestly: *what am I anchored to?*

If it's anything other than Jesus, tonight can be the night you tie your life to the One who will never move. Hebrews 13:5 says he will never leave you or forsake you.

**Prayer:** Lead the room in a simple prayer of response. Then invite students to talk with a leader in the back.

## Discussion Questions (Small Groups)

- What are some "anchors" people our age trust in?
- Which passage tonight stood out to you most? Why?
- Who is one person you can show unconditional love to this week?

Let's pray.`;
